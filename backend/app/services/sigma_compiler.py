import uuid
from datetime import UTC, datetime

import yaml

from app.schemas.cir import CIRNode, CIRSpecification
from app.services.attack_knowledge import TACTIC_NAMES
from app.services.detection_observables import ObservableGroup, node_observable_groups

_NAMESPACE = uuid.UUID("6f1d3c2a-9a51-4f2e-8a7c-1d2b3c4d5e6f")


def sigma_tags(node: CIRNode) -> list[str]:
    """Sigma-convention ATT&CK tags: attack.<tactic_name> and attack.t1234.001."""
    tags = []
    tactic_name = TACTIC_NAMES.get(str(node.tactic).upper())
    if tactic_name:
        tags.append("attack." + tactic_name.lower().replace(" ", "_"))
    if str(node.technique).upper().startswith("T"):
        tags.append("attack." + str(node.technique).lower())
    return tags


def _selection(group: ObservableGroup) -> dict:
    """Observables in a group are ANDed. Several values for the same string
    modifier use Sigma's "|all"; several exact values (e.g. IPs) become a list (OR)."""
    values: dict[tuple[str, str], list[str]] = {}
    for observable in group.observables:
        values.setdefault((observable.field, observable.op), []).append(observable.value)
    selection: dict[str, object] = {}
    for (field, op), items in values.items():
        key = field if op == "equals" else f"{field}|{op}"
        if len(items) == 1:
            selection[key] = items[0]
        elif op == "equals":
            selection[key] = items
        else:
            selection[f"{key}|all"] = items
    return selection


class SigmaCompiler:
    """
    Kompilator deterministik untuk mengubah CIR Graph menjadi Sigma Rules.
    Satu rule per (node, kategori telemetry); node tanpa observable dilewati
    dan dicatat di komentar header.
    """

    def __init__(self, cir_data: CIRSpecification):
        self.cir_data = cir_data

    def rules_for_node(self, node: CIRNode, scenario_id: str | None = None) -> list[dict]:
        scenario_id = scenario_id or self.cir_data.scenario_id
        by_category: dict[str, list[ObservableGroup]] = {}
        for group in node_observable_groups(node):
            by_category.setdefault(group.category, []).append(group)

        rules = []
        label = node.technique_name or node.action_type.replace("_", " ").title()
        for category, groups in by_category.items():
            if len(groups) == 1:
                detection = {"selection": _selection(groups[0]), "condition": "selection"}
            else:
                detection = {f"selection_{i}": _selection(g) for i, g in enumerate(groups, start=1)}
                detection["condition"] = "1 of selection_*"
            inferred = all(group.inferred for group in groups)
            rules.append({
                "title": f"{node.technique} {label} ({category.replace('_', ' ')})",
                "id": str(uuid.uuid5(_NAMESPACE, f"{scenario_id}:{node.step_id}:{category}")),
                "status": "experimental",
                "description": (
                    f"Generated by ThreatCanvas from CIR step {node.step_id} of scenario {scenario_id}."
                    + (" Observables were inferred from evidence text; review before deploying." if inferred else "")
                ),
                "author": "ThreatCanvas AI Engine",
                "date": datetime.now(UTC).strftime("%Y-%m-%d"),
                "tags": sigma_tags(node),
                "logsource": {"category": category, "product": "windows"},
                "detection": detection,
                "falsepositives": ["Legitimate administrative activity"],
                "level": "medium" if inferred else "high",
            })
        return rules

    def compile(self) -> str:
        """Mengompilasi seluruh node di CIR Graph menjadi dokumen YAML (Sigma)."""
        rules: list[dict] = []
        skipped: list[str] = []
        for node in self.cir_data.attack_graph.nodes:
            node_rules = self.rules_for_node(node)
            if node_rules:
                rules.extend(node_rules)
            else:
                skipped.append(f"{node.step_id} ({node.technique})")

        header = ""
        if skipped:
            header = "# ThreatCanvas: no detectable observable in evidence for steps: " + ", ".join(skipped) + "\n"
        yaml_docs = [yaml.safe_dump(rule, sort_keys=False, allow_unicode=True) for rule in rules]
        return header + "\n---\n".join(yaml_docs)
