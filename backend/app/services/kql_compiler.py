import yaml

from app.schemas.cir import CIRSpecification
from app.services.sigma_compiler import SigmaCompiler
from app.services.sigma_conversion import convert


def kql_string(value: str) -> str:
    """Double-quoted KQL string literal with backslash escaping."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


class KQLCompiler:
    """CIR -> Sigma (from evidence) -> KQL via the pySigma Kusto backend with
    the Microsoft Defender XDR pipeline. Rules are combined into one union and
    tagged with their CIR step / ATT&CK mapping."""

    def __init__(self, cir_data: CIRSpecification):
        self.cir_data = cir_data

    def compile(self) -> str:
        sigma = SigmaCompiler(self.cir_data)
        queries: list[str] = []
        notes: list[str] = []
        for node in self.cir_data.attack_graph.nodes:
            rules = sigma.rules_for_node(node)
            if not rules:
                notes.append(f"{node.step_id} ({node.technique}): no detectable observable in evidence")
                continue
            result = convert(yaml.safe_dump_all(rules, sort_keys=False), "kql")
            for rule in result.rules:
                if rule.error:
                    notes.append(f"{node.step_id} ({node.technique}): {rule.error}")
                    continue
                for query in rule.queries:
                    queries.append(
                        f"{query}\n| extend StepId={kql_string(node.step_id)}, "
                        f"Tactic={kql_string(node.tactic)}, Technique={kql_string(node.technique)}"
                    )

        header = ["// KQL (Microsoft Defender XDR / Sentinel) generated by ThreatCanvas via pySigma"]
        header += [f"// Skipped {note}" for note in notes]
        if not queries:
            return "\n".join(header)
        if len(queries) == 1:
            body = queries[0]
        else:
            body = "union\n" + ",\n".join("    (" + q.replace("\n", "\n     ") + ")" for q in queries)
        return "\n".join(header) + "\n" + body
